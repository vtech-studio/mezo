const maxImageBytes = 3 * 1024 * 1024

var cloudNamePattern = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,62}$`)

func imageRoute(path string) bool {
	return path == "/admin/r/:slug/logo" || path == "/admin/r/:slug/menu/:id/photo" || path == "/api/r/:slug/logo" || path == "/api/r/:slug/menu/:id/photo"
}

// The destination and public ID are generated by the server; URLs supplied by
// a browser are never fetched. Secrets are used only in the signed server call.
func cloudSignature(params map[string]string, secret string) string {
	keys := make([]string, 0, len(params))
	for k := range params {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	pairs := make([]string, 0, len(keys))
	for _, k := range keys {
		pairs = append(pairs, k+"="+params[k])
	}
	sum := sha256.Sum256([]byte(strings.Join(pairs, "&") + secret))
	return hex.EncodeToString(sum[:])
}
func (a *App) cloudRequest(ctx context.Context, action string, params map[string]string, file []byte) (map[string]any, error) {
	params["timestamp"] = strconv.FormatInt(time.Now().Unix(), 10)
	signature := cloudSignature(params, a.cfg.CloudSecret)
	var body bytes.Buffer
	w := multipart.NewWriter(&body)
	for k, v := range params {
		if err := w.WriteField(k, v); err != nil {
			return nil, err
		}
	}
	_ = w.WriteField("api_key", a.cfg.CloudKey)
	_ = w.WriteField("signature", signature)
	if file != nil {
		p, err := w.CreateFormFile("file", "image")
		if err != nil {
			return nil, err
		}
		if _, err = p.Write(file); err != nil {
			return nil, err
		}
	}
	if err := w.Close(); err != nil {
		return nil, err
	}
	req, err := http.NewRequestWithContext(ctx, "POST", "https://api.cloudinary.com/v1_1/"+a.cfg.CloudName+"/image/"+action, &body)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", w.FormDataContentType())
	client := a.imageClient
	if client == nil {
		client = &http.Client{Timeout: 25 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}
	}
	res, err := client.Do(req)
	if err != nil {
		return nil, errors.New("Cloudinary indisponível")
	}
	defer res.Body.Close()
	if res.StatusCode < 200 || res.StatusCode >= 300 {
		return nil, fmt.Errorf("Cloudinary retornou HTTP %d", res.StatusCode)
	}
	var out map[string]any
	if err = json.NewDecoder(io.LimitReader(res.Body, 64*1024)).Decode(&out); err != nil {
		return nil, errors.New("resposta de imagem inválida")
	}
	return out, nil
}
func validateImage(data []byte) error {
	if len(data) == 0 || len(data) > maxImageBytes {
		return errors.New("Escolha uma imagem de até 3 MB.")
	}
	cfg, format, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil || !(format == "jpeg" || format == "png" || format == "webp") {
		return errors.New("Escolha uma imagem JPG, PNG ou WebP válida.")
	}
	if cfg.Width <= 0 || cfg.Height <= 0 || int64(cfg.Width)*int64(cfg.Height) > 24000000 {
		return errors.New("A imagem deve ter até 24 megapixels.")
	}
	// Decode the complete file as well: headers alone do not establish validity.
	if _, _, err = image.Decode(bytes.NewReader(data)); err != nil {
		return errors.New("A imagem está incompleta ou inválida.")
	}
	return nil
}
func (a *App) uploadImage(c echo.Context) error {
	c.Request().Body = http.MaxBytesReader(c.Response(), c.Request().Body, maxImageBytes+64*1024)
	defer func() {
		// Vercel forwards multipart requests to the Go process. Drain the bounded
		// body on early auth failures so its proxy can finish writing and receive
		// the 401/403 response, instead of a broken-pipe 502.
		_, _ = io.Copy(io.Discard, c.Request().Body)
		if c.Request().MultipartForm != nil {
			_ = c.Request().MultipartForm.RemoveAll()
		}
	}()
	h, err := a.houseAccess(c, true)
	if err != nil {
		return err
	}
	defer h.Release()
	t, p := h.Tenant, h.Pool
	if a.cfg.CloudName == "" {
		return echo.NewHTTPError(503, "O envio de imagens ainda não foi configurado.")
	}
	ctx, cancel := context.WithTimeout(c.Request().Context(), 30*time.Second)
	defer cancel()
	id := c.Param("id")
	kind := "logo"
	if id != "" {
		kind = "menu"
		var exists bool
		if err = p.QueryRow(ctx, "SELECT EXISTS(SELECT 1 FROM menu_items WHERE id=$1)", id).Scan(&exists); err != nil {
			return err
		}
		if !exists {
			return echo.ErrNotFound
		}
	}
	// MaxBytesReader also bounds chunked requests before multipart parsing.
	if err = c.Request().ParseMultipartForm(64 * 1024); err != nil {
		return echo.NewHTTPError(400, "Não foi possível ler a imagem. Use um arquivo de até 3 MB.")
	}
	f, _, err := c.Request().FormFile("image")
	if err != nil {
		return echo.NewHTTPError(400, "Escolha a imagem para enviar.")
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, maxImageBytes+1))
	if err != nil {
		return echo.NewHTTPError(400, "Não foi possível ler a imagem.")
	}
	if err = validateImage(data); err != nil {
		return echo.NewHTTPError(400, err.Error())
	}
	publicID := "mezo/" + t.ID + "/" + kind + "/" + randomID()
	result, err := a.cloudRequest(ctx, "upload", map[string]string{"public_id": publicID, "overwrite": "false", "allowed_formats": "jpg,png,webp", "transformation": "c_limit,w_1600,h_1600"}, data)
	if err != nil {
		return echo.NewHTTPError(502, "Não foi possível enviar ao Cloudinary. Tente novamente.")
	}
	imageURL, _ := result["secure_url"].(string)
	returnedID, _ := result["public_id"].(string)
	u, parseErr := url.Parse(imageURL)
	if parseErr != nil || u.Scheme != "https" || u.Host != "res.cloudinary.com" || !strings.HasPrefix(u.Path, "/"+a.cfg.CloudName+"/image/upload/") || returnedID != publicID {
		return echo.NewHTTPError(502, "O serviço retornou uma imagem inválida.")
	}
	if kind == "logo" {
		_, err = p.Exec(ctx, "UPDATE restaurant_brand SET logo_url=$1,logo_public_id=$2 WHERE singleton", imageURL, publicID)
	} else {
		var tag pgconn.CommandTag
		tag, err = p.Exec(ctx, "UPDATE menu_items SET image_url=$2,image_public_id=$3 WHERE id=$1", id, imageURL, publicID)
		if err == nil && tag.RowsAffected() != 1 {
			err = pgx.ErrNoRows
		}
	}
	if err != nil {
		// Only this freshly created asset is eligible for rollback cleanup.
		clean, c := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
		defer c()
		_, _ = a.cloudRequest(clean, "destroy", map[string]string{"public_id": publicID, "invalidate": "true"}, nil)
		return echo.NewHTTPError(500, "A imagem não foi salva no restaurante. Tente novamente.")
	}
	a.notify(ctx, t.ID, "")
	if c.Request().Header.Get("HX-Request") != "true" {
		if strings.HasPrefix(c.Path(), "/admin/") {
			return c.Redirect(303, "/admin")
		}
		return c.Redirect(303, "/r/"+t.Slug+"/imagens")
	}
	return c.HTML(200, "<p class='notice' role='status'>Imagem salva.</p><img class='media-preview' src='"+template.HTMLEscapeString(imageURL)+"' alt='Imagem salva no restaurante'>")
}
func (a *App) imagesPage(c echo.Context) error {
	h, err := a.houseAccess(c, false)
	if err != nil {
		return loginRedirect(c, err)
	}
	defer h.Release()
	t, p, csrf := h.Tenant, h.Pool, h.CSRF
	var logo string
	if err = p.QueryRow(c.Request().Context(), "SELECT logo_url FROM restaurant_brand WHERE singleton").Scan(&logo); err != nil {
		return err
	}
	rows, err := p.Query(c.Request().Context(), "SELECT id,name,image_url FROM menu_items ORDER BY name")
	if err != nil {
		return err
	}
	defer rows.Close()
	menu := []map[string]string{}
	for rows.Next() {
		var id, name, img string
		if err = rows.Scan(&id, &name, &img); err != nil {
			return err
		}
		menu = append(menu, map[string]string{"ID": id, "Name": name, "ImageURL": img})
	}
	if err = rows.Err(); err != nil {
		return err
	}
	return a.renderTemplate(c, "images.html", map[string]any{"Name": t.Name, "Slug": t.Slug, "LogoURL": logo, "Menu": menu, "CSRF": csrf, "ImagesEnabled": a.cfg.CloudName != ""})
}
